export interface CellDifferential {
  // 粒细胞系统
  myeloblast: number; // 原始粒
  promyelocyte: number; // 早幼粒
  myelocyteNeutro: number; // 中幼粒(中性)
  metamyelocyteNeutro: number; // 晚幼粒(中性)
  bandNeutro: number; // 杆状核(中性)
  segmentedNeutro: number; // 分叶核(中性)
  
  myelocyteEos: number; // 中幼(嗜酸)
  metamyelocyteEos: number; // 晚幼(嗜酸)
  bandEos: number; // 杆状核(嗜酸)
  segmentedEos: number; // 分叶核(嗜酸)

  myelocyteBaso: number; // 中幼(嗜碱)
  metamyelocyteBaso: number; // 晚幼(嗜碱)
  bandBaso: number; // 杆状核(嗜碱)
  segmentedBaso: number; // 分叶核(嗜碱)

  // 红细胞系统
  pronormoblast: number; // 原始红
  basophilicNormoblast: number; // 早幼红
  polychromaticNormoblast: number; // 中幼红
  orthochromaticNormoblast: number; // 晚幼红
  giantPronormoblast: number; // 巨原始红
  giantPolychromatic: number; // 巨中幼红
  giantOrthochromatic: number; // 巨晚幼红

  // 淋巴细胞系统
  lymphoblast: number; // 原始淋巴
  prolymphocyte: number; // 幼稚淋巴
  matureLymphocyte: number; // 成熟淋巴
  atypicalLymphocyte: number; // 异型淋巴
  lymphosarcomaCell: number; // 淋巴肉瘤细胞

  // 单核细胞系统
  monoblast: number; // 原始单核
  promonocyte: number; // 幼稚单核
  matureMonocyte: number; // 成熟单核

  // 浆细胞系统
  plasmablast: number; // 原始浆
  proplasmacyte: number; // 幼稚浆
  maturePlasmacyte: number; // 成熟浆

  // 巨核细胞系统
  megakaryoblast: number; // 原始巨核
  promegakaryocyte: number; // 幼稚巨核
  granularMegakaryocyte: number; // 颗粒型巨核
  thrombocytogenicMegakaryocyte: number; // 产板型巨核
  bareNucleusMegakaryocyte: number; // 裸核型巨核

  // 网状及其他细胞
  reticularCell: number; // 网状细胞
  tissueBasophil: number; // 组织嗜碱细胞
  macrophage: number; // 吞噬细胞
  myelomaCell: number; // 骨髓瘤细胞
  fatCell: number; // 脂肪细胞
  unclassifiedCell: number; // 分类不明细胞

  marrowTotal: number; // 髓片总数 (默认200)
  bloodTotal: number; // 血片总数 (默认100)
  currentMarrowCount: number; // 当前已计髓片数
  currentBloodCount: number; // 当前已计血片数
}

export interface CytochemicalStaining {
  napScore: number; // NAP积分值 (0-400)
  napPositiveRate: string; // NAP阳性率 %
  pox: string; // POX过氧化物酶 (如 "强阳性 +++")
  pas: string; // PAS糖原染色 (如 "弥漫阳性 ++")
  nea: string; // NEA非特异性酯酶 (如 "弱阳性 +")
  naeNaf: string; // NAE-NAF抑制试验 (如 "被NAF抑制 >80%")
  extracellularIron: string; // 细胞外铁 (如 "++")
  intracellularIron: {
    i: number; // Ⅰ型 %
    ii: number; // Ⅱ型 %
    iii: number; // Ⅲ型 %
    iv: number; // Ⅳ型 %
    ring: number; // 环铁 %
  };
}

