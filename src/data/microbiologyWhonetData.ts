  gender: '男' | '女'; // 性别
  age: string; // 年龄
  specimen: string; // 标本
  department: string; // 科室
  diagnosis: string; // 诊断
  reportTime: string; // 报告时间 (近期时间 2026年10月)
  sampleTime: string; // 采样时间
