export interface WhonetAntibioticResult {
  drugCode: string; // WHONET 抗生素缩写 (如 AMP, MEM, CIP, VAN, LZD)
  drugName: string; // 中文名称 (如 氨苄西林, 美罗培南, 环丙沙星, 万古霉素, 利奈唑胺)
  micOrDisk: string; // 实测值 (如 <=0.25 ug/mL 或 26 mm)
  interp: 'S' | 'I' | 'R' | 'SDD'; // 解释 (敏感 / 中介 / 耐药 / 剂量依赖敏感)
}

